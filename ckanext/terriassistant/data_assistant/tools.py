"""Closed tool vocabulary, also advertised to the browser as capabilities."""
import json

from jsonschema import Draft7Validator


def obj(properties, required=()):
    return dict(type="object", properties=properties, required=list(required), additionalProperties=False)


STRING = dict(type="string", maxLength=200)
SOURCE = dict(type="string", maxLength=300)
NUMBER = dict(type="number")
FILTER = obj({
    "column": STRING,
    "op": dict(enum=["eq", "ne", "lt", "lte", "gt", "gte", "in", "contains"]),
    "value": {"type": ["string", "number", "boolean", "null", "array"],
              "items": {"type": ["string", "number", "boolean", "null"]}, "maxItems": 100},
}, ["column", "op", "value"])
QUERY = obj({
    "source_id": SOURCE,
    "operation": dict(enum=["rows", "statistics", "group", "time_series", "trend", "correlation", "outliers"]),
    "column": STRING, "column2": STRING, "date_column": STRING, "group_by": STRING,
    "columns": dict(type="array", items=STRING, maxItems=20),
    "filters": dict(type="array", items=FILTER, maxItems=20),
    "start": dict(type="string", maxLength=40), "end": dict(type="string", maxLength=40),
    "period": dict(enum=["day", "month", "year"]),
    "metric": dict(enum=["count", "sum", "mean", "median", "min", "max", "stddev"]),
    "limit": dict(type="integer", minimum=1, maximum=200),
    "offset": dict(type="integer", minimum=0, maximum=150000),
    "order_by": STRING, "descending": dict(type="boolean"),
    "polygon": obj({"type": {"const": "Polygon"}, "coordinates": {
        "type": "array", "minItems": 1, "maxItems": 20, "items": {
            "type": "array", "minItems": 4, "maxItems": 1000, "items": {
                "type": "array", "items": NUMBER, "minItems": 2, "maxItems": 2}}}}, ["type", "coordinates"]),
    "point": dict(type="array", items=NUMBER, minItems=2, maxItems=2),
    "latitude_column": STRING, "longitude_column": STRING,
    "band": dict(type="integer", minimum=1, maximum=100),
}, ["source_id", "operation"])

SCHEMAS = {
    "search_catalog": obj({"query": dict(type="string", maxLength=500),
                           "limit": dict(type="integer", minimum=1, maximum=10)}, ["query"]),
    "describe_source": obj({"source_id": SOURCE}, ["source_id"]),
    "query_data": QUERY,
    "compare_results": obj({"left_id": STRING, "right_id": STRING,
                            "operation": dict(enum=["difference", "correlation"])},
                           ["left_id", "right_id", "operation"]),
    "present_result": obj({"result_id": STRING, "title": STRING,
                           "chart": dict(enum=["table", "line", "bar", "scatter"])}, ["result_id", "chart"]),
    "suggest_map_action": obj({"source_id": SOURCE,
                               "action": dict(enum=["add_layer", "zoom", "filter"]),
                               "title": STRING,
                               "filters": QUERY["properties"]["filters"],
                               "start": STRING, "end": STRING, "date_column": STRING}, ["source_id", "action"]),
}
DESCRIPTIONS = {
    "search_catalog": "Search the authorized IHP CKAN catalog for datasets and resources. Query uses CKAN search syntax; use short subject terms.",
    "describe_source": "Inspect metadata and exact column names, types, units and coverage before calculating. Sources may be CKAN resources or loaded Terria layers.",
    "query_data": "Calculate on a complete permitted data source, never on the describe sample. Statistics, filtered rows/rankings, grouped aggregates, time series, annual trend, Pearson correlation or IQR outliers. Spatial filter uses a WGS84 polygon. COG layers require a selected/supplied point or polygon; use time_series for multiple dates. Nulls are excluded; statistics include coverage. Use separate queries and compare_results for different periods/sources. No code or SQL.",
    "compare_results": "Compare computed evidence: difference and percentage between means, or Pearson correlation of series aligned on exact x/time keys. Never establishes causation. Inputs must have matching units for differences.",
    "present_result": "Display a table/chart and CSV made from a prior computed result. Values are taken from that result, not generated by the model.",
    "suggest_map_action": "Offer a button to add a CKAN resource, zoom to a loaded layer, or apply a filter. Does not change the map until the user clicks.",
}
TOOLS = [{"type": "function", "function": {"name": name, "description": DESCRIPTIONS[name], "parameters": schema}}
         for name, schema in SCHEMAS.items()]


def validate_call(name, arguments):
    if name not in SCHEMAS:
        raise ValueError("Unknown tool")
    if isinstance(arguments, str):
        if len(arguments) > 100000:
            raise ValueError("Tool arguments too large")
        arguments = json.loads(arguments)
    Draft7Validator(SCHEMAS[name]).validate(arguments)
    return arguments
